def live_streams():
    out = []
    for i, n in enumerate(CHANNEL_NAMES):
        out.append({
            "num": i + 1,
            "name": n,
            "stream_id": i + 1,
            "stream_icon": "",
            "category_id": LIVE_CATS[i % 4]["category_id"],
            "epg_channel_id": "",
        })
    return out


def vod_streams():
    out = []
    for i, n in enumerate(MOVIE_NAMES):
        out.append({
            "name": n,
            "stream_id": 1000 + i,
            "category_id": VOD_CATS[i % 3]["category_id"],
            "cover": "",
            "stream_icon": "",
            "rating": "%d.%d" % (6 + i % 3, i % 9),
            "container_extension": "mkv",
            "plot": LONG_PLOT_DE if i == 0 else "",
        })
    return out


def series_list():
    out = []
    for i, (sid, name, plot) in enumerate(SERIES):
        out.append({
            "name": name,
            "series_id": sid,
            "category_id": SERIES_CATS[i % 2]["category_id"],
            "cover": "",
            "plot": plot,
        })
    return out


def series_info(sid):
    # Series 2002 is the "one season, one episode" fixture. The hero's meta line
    # has nothing to say there — the only sentence it could produce is
    # "1 Folge", which repeats the single row directly below it — so the app
    # must render no meta line at all. Its plot stays MIXED_PLOT, which makes it
    # a harder case than a short one: the line is missing while there is plenty
    # of text above it.
    if sid == 2002:
        return {"episodes": {"1": [{
            "id": sid * 10 + 1,
            "title": "Pilot",
            "season": "1",
            "episode": "1",
            "container_extension": "mkv",
        }]}}
    eps = {}
    for season in (1, 2):
        key = str(season)
        eps[key] = [{
            "id": sid * 10 + season * 3 + e,
            "title": "Folge %d" % (e + 1),
            "season": str(season),
            "episode": str(e + 1),
            "container_extension": "mkv",
        } for e in range(3)]
    return {"episodes": eps}


# --- M3U fixtures for the login-link regression QA -------------------------
# /liste.m3u  : full playlist with EXTINF metadata
# /bare.m3u   : plain "one URL per line" playlist (no EXTINF at all)
# /empty.m3u  : valid HTTP 200 but no channels -> must show a clear error
# /bad.m3u    : HTML error page -> must not be parsed into junk channels
M3U_LINKS = "http://10.0.2.2:8899/live/%d.ts"
M3U_FULL = (
    "#EXTM3U\n"
    '#EXTINF:-1 tvg-logo="http://10.0.2.2:8899/logo.png" '
    'group-title="Nachrichten",ARD HD\n' + (M3U_LINKS % 1) + "\n"
    '#EXTINF:-1 group-title="Sport",ZDF HD\n' + (M3U_LINKS % 2) + "\n"
)
M3U_BARE = "#EXTM3U\n" + (M3U_LINKS % 3) + "\n" + (M3U_LINKS % 4) + "\n"
M3U_EMPTY = "#EXTM3U\n# Keine Sender in dieser Liste\n"
M3U_HTML = "<!doctype html><html><body>404 Not Found</body></html>"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        sys.stderr.write("[stub] %s %s\n" % (self.command, self.path))
        sys.stderr.flush()

    def send_json(self, obj):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def send_text(self, status, body, content_type):
        raw = body.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def send_avi(self, head_only=False):
        """Serve the clip with byte ranges: ffmpeg seeks to AVI's idx1 index."""
        size = len(AVI_BYTES)
        start, end, status = 0, size - 1, 200
        rng = self.headers.get("Range", "")
        if rng.startswith("bytes="):
            spec = rng[6:].split(",")[0].strip()
            if "-" in spec:
                a, b = spec.split("-", 1)
                if a:
                    start = int(a)
                    if b:
                        end = min(int(b), size - 1)
                elif b:
                    start = max(0, size - int(b))
                status = 206
        if start >= size:
            self.send_response(416)
            self.send_header("Content-Range", "bytes */%d" % size)
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        chunk = AVI_BYTES[start:end + 1]
        self.send_response(status)
        self.send_header("Content-Type", "video/avi")
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(len(chunk)))
        if status == 206:
            self.send_header(
                "Content-Range", "bytes %d-%d/%d" % (start, end, size)
            )
        self.end_headers()
        if not head_only:
            self.wfile.write(chunk)

    def do_HEAD(self):
        u = urlparse(self.path)
        if AVI_BYTES and u.path.startswith(MEDIA_PREFIXES):
            self.send_avi(head_only=True)
            return
        self.send_response(200)
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self):
        u = urlparse(self.path)
        q = parse_qs(u.query)
        action = (q.get("action") or [""])[0]

        # Real bytes behind every generated stream URL. The Xtream builder puts
        # username/password into the path, and the M3U fixture uses /live/N.ts;
        # both are covered by the prefix check.
        if AVI_BYTES and u.path.startswith(MEDIA_PREFIXES):
            self.send_avi()
            return

        playlists = {
            "/liste.m3u": M3U_FULL,
            "/bare.m3u": M3U_BARE,
            "/empty.m3u": M3U_EMPTY,
        }
        if u.path in playlists:
            self.send_text(200, playlists[u.path], "audio/x-mpegurl; charset=utf-8")
            return
        if u.path == "/bad.m3u":
            self.send_text(404, M3U_HTML, "text/html; charset=utf-8")
            return

        if u.path != "/player_api.php":
            self.send_json({})
            return

        if action == "get_live_categories":
            self.send_json(LIVE_CATS)
        elif action == "get_vod_categories":
            self.send_json(VOD_CATS)
        elif action == "get_series_categories":
            self.send_json(SERIES_CATS)
        elif action == "get_live_streams":
            self.send_json(live_streams())
        elif action == "get_vod_streams":
            self.send_json(vod_streams())
        elif action == "get_series":
            self.send_json(series_list())
        elif action == "get_series_info":
            sid = int((q.get("series_id") or ["0"])[0])
            self.send_json(series_info(sid))
        elif action in ("get_short_epg", "get_simple_data_table"):
            import time
            base = int(time.time()) // 1800 * 1800
            names = ["Nachrichten", "Wetter", "Dokumentation", "Abendfilm", "Kulturmagazin", "Spätausgabe", "Nachtjournal", "Morgenmagazin"]
            self.send_json({"epg_listings": [
                {"title": name, "description": "Programmübersicht für den EPG-Zeitstrahl.",
                 "start_timestamp": str(base + i * 3600), "stop_timestamp": str(base + (i + 1) * 3600)}
                for i, name in enumerate(names)
            ]})
        else:
            # Bare login call: auth must be 1. server_info.url empty keeps the
            # stream base on http://10.0.2.2:8899 (no https_port rewrite).
            self.send_json({
                "user_info": {"auth": 1, "username": "probe", "status": "Active"},
                "server_info": {"url": "", "https_port": ""},
            })


if __name__ == "__main__":
    srv = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    sys.stderr.write("[stub] listening on 0.0.0.0:%d\n" % PORT)
    sys.stderr.flush()
    srv.serve_forever()

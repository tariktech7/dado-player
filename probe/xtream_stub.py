#!/usr/bin/env python3
"""Probe fixture: a minimal Xtream-Codes API so the Android build can be driven
into its content screens without a provider account and without a rebuild.

Why this exists
---------------
`IPTV_DEMO` is read with `std::env::var` (src/app.rs:196). Injecting an env var
into a zygote-spawned process needs `setprop wrap.<pkg>`, and that wrap replaces
the ARM64-translated `app_process64` with an x86_64 binary, so the process can
no longer dlopen `lib/arm64-v8a/libdadoplayer.so`:

    UnsatisfiedLinkError: dlopen failed: ".../libdadoplayer.so" is for
    EM_AARCH64 (183) instead of EM_X86_64 (62)

So the demo path is unreachable on the x86_64 emulator. This stub instead feeds
the real Xtream code path (src/client.rs:195-287) over http://10.0.2.2:8899,
which also lets the *plot length* be chosen freely - the demo fixture's 44-char
plot is too short to make a row cap observable.

Probe-only. Not part of the app build, not shipped.
"""

import json
import os
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

PORT = 8899

# A real playable clip for the stream URLs the app builds. The generated
# uncompressed RGB24 AVI is self-describing, so libmpv can demux it even though
# the URL ends in .ts / .mkv. Without this the stub returned `{}` for every
# /live/... and /series/... path, which made it impossible to distinguish a
# broken URL from a fixture that simply had no media behind it.
#
# Generated by Rust's `test_pattern::write`; copy it next to this script with:
#   cp "$TEMP/dado-player-test.avi" probe/fixture.avi
AVI_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixture.avi")
try:
    with open(AVI_PATH, "rb") as _f:
        AVI_BYTES = _f.read()
except OSError:
    AVI_BYTES = b""
    sys.stderr.write("[stub] no fixture.avi - stream URLs will be empty\n")

# All three Xtream stream families plus the M3U fixture links must resolve.
MEDIA_PREFIXES = ("/live/", "/movie/", "/series/")

# ~300 characters. Under the old character cap (take 180) this is ~5 lines at
# 411 dp; under a 3-row cap it must be exactly 3 lines plus an ellipsis.

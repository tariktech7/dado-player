"""Synchronize or check product version metadata without changing app identities."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def github_release_tag(release):
    tag = f'v{release["version"]}'
    if release["channel"] == "stable":
        return tag
    beta = release.get("betaNumber")
    if release["channel"] != "beta" or type(beta) is not int or beta < 1:
        raise ValueError("A beta requires a positive betaNumber")
    return f"{tag}-beta" if beta == 1 else f"{tag}-beta.{beta}"


def updates():
    release = json.loads((ROOT / "release.json").read_text(encoding="utf-8"))
    version = release["version"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Invalid product version")
    tag = github_release_tag(release)
    for key in ("androidBuild", "iosBuild", "windowsBuild", "tizenBuild"):
        if not isinstance(release[key], int) or release[key] <= 0:
            raise ValueError(f"Invalid {key}")
    result = {}
    readme = ROOT / "README.md"
    label = f'{version} Beta {release["betaNumber"]}' if release["channel"] == "beta" else version
    download_line = (
        "Gemeinsamer Download für Windows, Android, iOS und Samsung Tizen: "
        f"[**{label}**](https://github.com/tariktech7/dado-player/releases/tag/{tag})."
    )
    result[readme], count = re.subn(
        r"(?m)^Gemeinsamer Download für Windows, Android, iOS und Samsung Tizen:.*$",
        download_line,
        readme.read_text(encoding="utf-8"),
    )
    if count != 1:
        raise ValueError("Expected exactly one shared download link in README.md")
    cargo = ROOT / "Cargo.toml"
    result[cargo] = re.sub(r'(?m)^version = "[^"]+"', f'version = "{version}"', cargo.read_text(encoding="utf-8"), count=1)
    result[ROOT / "windows/VERSION"] = version + "\n"
    for name in ("package.json", "package-lock.json"):
        file = ROOT / "SmartTV/client" / name
        value = json.loads(file.read_text(encoding="utf-8"))
        value["version"] = version
        if "packages" in value:
            value["packages"][""]["version"] = version
        result[file] = json.dumps(value, indent=2) + "\n"
    gradle = ROOT / "android/app/build.gradle"
    text = re.sub(r'versionName "[^"]+"', f'versionName "{version}"', gradle.read_text(encoding="utf-8"))
    result[gradle] = re.sub(r"versionCode \d+", f'versionCode {release["androidBuild"]}', text)
    plist = ROOT / "ios/Info.plist"
    text = plist.read_text(encoding="utf-8")
    for key, value in (("CFBundleShortVersionString", version), ("CFBundleVersion", str(release["iosBuild"]))):
        text = re.sub(rf'(<key>{key}</key>\s*<string>)[^<]+', lambda m: m[1] + value, text)
    result[plist] = text
    policy = json.loads((ROOT / "shared/product-policy.json").read_text(encoding="utf-8"))
    result[ROOT / "src/release_info.rs"] = (
        "// Generated by scripts/release_version.py from release.json.\n"
        f'pub const VERSION: &str = "{version}";\n'
        f'pub const RELEASE_NAME: &str = "{label}";\n'
        f'pub const ANDROID_BUILD: u32 = {release["androidBuild"]};\n'
        f'pub const IOS_BUILD: u32 = {release["iosBuild"]};\n'
        f'pub const WINDOWS_BUILD: u32 = {release["windowsBuild"]};\n'
        f'pub const RESUME_MINIMUM_SECONDS: u64 = {policy["resumeMinimumSeconds"]};\n'
        f'pub const RESUME_END_MARGIN_SECONDS: u64 = {policy["resumeEndMarginSeconds"]};\n'
        f'pub const SEEK_STEP_SECONDS: f64 = {policy["seekStepSeconds"]:.1f};\n'
        f'pub const CONTROLS_HIDE_SECONDS: f64 = {policy["controlsHideMs"] / 1000:.1f};\n'
        f'pub const HISTORY_LIMIT: usize = {policy["historyLimit"]};\n'
        f'pub const AUTOPLAY_LAST: bool = {str(policy["autoplayLast"]).lower()};\n'
    )
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tag", action="store_true")
    args = parser.parse_args()
    if args.tag:
        print(github_release_tag(json.loads((ROOT / "release.json").read_text(encoding="utf-8"))))
        return
    changed = []
    for file, desired in updates().items():
        actual = file.read_text(encoding="utf-8") if file.exists() else None
        if actual != desired:
            changed.append(str(file.relative_to(ROOT)))
            if not args.check:
                file.write_text(desired, encoding="utf-8")
    if args.check and changed:
        raise SystemExit("Version metadata differs: " + ", ".join(changed) + ". Run python scripts/release_version.py")
    print("Product version metadata consistent" if args.check else "Synchronized: " + ", ".join(changed))


if __name__ == "__main__":
    main()
